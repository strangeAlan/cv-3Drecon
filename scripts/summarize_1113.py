"""Summary of the 11/13 runs (DA3-BA, VGGT-BA, COLMAP-RADIAL) next to the 10/27-10/28 baselines, on the same cases.

Reads results/{1027-main,1028-allviews,1113-main,1113-allviews,1113-da3ba-explore}/metrics.csv (whatever exists)
and writes results/1113-summary.md: per sampling x view count, mean metrics per method over the cases that every
listed method has; per-case wins of DA3-BA over DA3; the exploration table.

Usage: python scripts/summarize_1113.py
"""
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
ORDER = ["colmap", "colmap_radial", "vggt", "vggtba", "vggtba_ds", "da3", "da3ba", "da3ba_ds", "hybrid_da3ba",
         "hybrid_da3ba_fill"]
COLS = ["reg_rate", "posefail_auc05", "posefail_auc30", "fscore_pc@0.02", "fscore_pc@0.05", "fscore_pc@0.10",
        "precision_pc@0.05", "recall_pc@0.05", "time_s"]
KEY = ["scene", "sampling", "n_views", "seed"]


def load(*runs):
    parts = [pd.read_csv(ROOT / "results" / r / "metrics.csv") for r in runs
             if (ROOT / "results" / r / "metrics.csv").exists()]
    if not parts:
        return None
    d = pd.concat(parts, ignore_index=True)
    d["n_views"] = d.n_views.astype(str)
    d["reg_rate"] = d.n_registered / d.n_input
    for c in COLS:
        if c not in d:
            d[c] = np.nan
    for c in [c for c in COLS if c.startswith(("fscore", "precision", "recall"))]:
        d[c] = d[c].fillna(0.0)
    return d.drop_duplicates(KEY + ["method"], keep="last")


def md(df, index=False):
    """Fixed-width table in a code block (no tabulate dependency)."""
    return "```\n" + df.to_string(index=index) + "\n```"


def table(d, methods, title):
    d = d[d.method.isin(methods)]
    have = d.groupby(KEY).method.nunique()
    full = have[have == d.method.nunique()].index
    d = d.set_index(KEY).loc[full].reset_index()
    g = d.groupby(["sampling", "n_views", "method"])[COLS].mean()
    g["n"] = d.groupby(["sampling", "n_views", "method"]).size()
    g = g.reset_index()
    g["_m"] = g.method.map({m: i for i, m in enumerate(ORDER)})
    g["_v"] = g.n_views.map({"5": 0, "10": 1, "20": 2, "all": 3})
    g = g.sort_values(["sampling", "_v", "_m"]).drop(columns=["_m", "_v"])
    for c in COLS[:-1]:
        g[c] = (100 * g[c]).round(1)
    g["time_s"] = g.time_s.round(1)
    allrow = d.groupby("method")[COLS].mean()
    allrow = allrow.reindex([m for m in ORDER if m in allrow.index])
    for c in COLS[:-1]:
        allrow[c] = (100 * allrow[c]).round(1)
    allrow["time_s"] = allrow.time_s.round(1)
    return (f"## {title}\n\n{len(full)} cases with all of: {', '.join(m for m in ORDER if m in methods and m in set(d.method))}"
            f" (values in %, time in s)\n\n" + md(g) + "\n\nAll cases:\n\n"
            + md(allrow, index=True) + "\n")


def wins(d, a, b, col="posefail_auc05"):
    p = d[d.method.isin([a, b])].pivot_table(index=KEY, columns="method", values=col)
    if a not in p or b not in p or p.dropna().empty:
        return ""
    p = p.dropna()
    diff = p[a] - p[b]
    return (f"- {a} vs {b} ({col}, {len(p)} cases): better {int((diff > 0.005).sum())}, tie "
            f"{int((diff.abs() <= 0.005).sum())}, worse {int((diff < -0.005).sum())}; mean diff {100 * diff.mean():+.1f}\n")


def main():
    out = ["# 11/13 runs: summary (auto-generated by scripts/summarize_1113.py)\n"]
    main_d = load("1027-main", "1113-main")
    if main_d is not None:
        main_d = main_d[main_d.sampling != "all"]
        out.append(table(main_d, ORDER, "Subsets (1027-main manifest)"))
        out.append(table(main_d, ["colmap", "colmap_radial", "vggt", "vggtba", "da3", "da3ba"],
                         "Subsets, sparse methods only (more cases while the dense stage is missing)"))
    all_d = load("1028-allviews", "1113-allviews")
    if all_d is not None:
        out.append(table(all_d, ORDER, "All views"))
    lines = []
    for d in [x for x in (main_d, all_d) if x is not None]:
        for a, b in [("da3ba", "da3"), ("vggtba", "vggt"), ("da3ba", "colmap_radial"), ("colmap_radial", "colmap")]:
            lines.append(wins(d, a, b))
        lines.append(wins(d, "hybrid_da3ba_fill", "da3", "fscore_pc@0.02"))
    out.append("## Per-case comparisons (subsets first, then all views)\n\n" + "".join(lines))
    ex = load("1027-main", "1113-da3ba-explore")
    if ex is not None and (ROOT / "manifests" / "1113-da3ba-explore.json").exists():
        import json
        cases = json.load(open(ROOT / "manifests" / "1113-da3ba-explore.json"))["cases"]
        keys = pd.DataFrame([{k: str(c[k]) if k == "n_views" else c[k] for k in KEY} | {"group": c["group"]}
                             for c in cases])
        ex = ex.merge(keys, on=KEY)
        p = ex.pivot_table(index=["group", "scene", "sampling", "n_views"], columns="method",
                           values=["posefail_auc05", "fscore_pc@0.02"])
        out.append("## Exploration set (13 cases)\n\n" + md((100 * p).round(1), index=True) + "\n")
    (ROOT / "results" / "1113-summary.md").write_text("\n".join(out))
    print("->", ROOT / "results" / "1113-summary.md")


if __name__ == "__main__":
    main()
